import { writeFile } from "node:fs/promises";

// Keep Apache's encoding and error page in sync with each deployment's base.
// No SPA rewrite: every route already has its own index.html.
export default function apacheStaticHosting() {
  let base;
  return {
    name: "website-apache",
    hooks: {
      "astro:config:done": ({ config }) => {
        base = config.base.endsWith("/") ? config.base : `${config.base}/`;
      },
      "astro:build:done": async ({ dir }) => {
        await writeFile(
          new URL(".htaccess", dir),
          `# Generated by the site build. Publish this file together with index.html.
AddDefaultCharset UTF-8
DirectoryIndex index.html
ErrorDocument 404 ${base}404.html

<IfModule mod_mime.c>
  AddCharset UTF-8 .html .css .js .mjs .txt .svg
  AddType text/css .css
  AddType text/javascript .js .mjs
  AddType image/svg+xml .svg
  AddType font/woff2 .woff2
</IfModule>
`,
        );
      },
    },
  };
}
